/**
 * The five guild-trial message types, verbatim from a guildmate's raw recording.
 *
 * 81,725 events across one full trial hour of a 30-player guild — a Crafting
 * skilling trial ending, then a Trial Badger combat trial through nine tiers.
 * These are the samples the extraction report preserved, kept as the game sent
 * them so that every rule built on them is a rule about real traffic.
 *
 * What each one settles:
 *
 * - **`new_guild_battle`** fires at *every tier* and carries the whole roster in
 *   array order, with `character.id` and `character.name` on each entry. A tick's
 *   `pMap` keys are indexes into that array — entry 19 is Player20 — which is
 *   the primary answer to "who is unit 19" that the spectator stream never had.
 *   Its `monsters[]` are full tier-scaled sheets, so a boss sheet no longer needs
 *   a click; and 30 players against a 330,000-health Badger giving 429,000 is the
 *   participant rule exact once more (`330,000 × 1.30`).
 * - **`guild_battle_updated`** carries action counters for **one** player in
 *   this recording — the recording client's own unit, index 19. That is a fact
 *   about this capture and no longer about the game: a later replay of a
 *   150,642-tick trial has counters on every present player, all 57 slots, in
 *   every tick bucket. Nothing may generalise "one counted slot" from here.
 * - **`guild_skilling_updated`** is the skilling half the DOM was being scraped
 *   for: pool, tier, participants by character id, and the per-tier personal
 *   figures (`successRate`, `efficiency`, `progressPerAction`, `actionTimeMs`).
 *   17 participants against a 76,000-work Crafting pool giving 88,920 is the pool
 *   rule exact (`76,000 × 1.17`).
 * - **`end_guild_battle`** and **`end_guild_skilling`** are the lifecycle. The
 *   skilling one states `tier: 9` while tier 10 was in progress — the game's own
 *   confirmation that a stated tier counts what is *banked*.
 *
 * The roster below is the full thirty, because the index join is the point of it.
 */

